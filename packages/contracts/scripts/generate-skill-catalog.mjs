#!/usr/bin/env node
/**
 * Writes src/operations/skill-catalog.generated.ts from skills/manifest.json (name, version, surfaces and
 * operations of every skill) and the `description` in each skill's SKILL.md frontmatter. `describe` serves this
 * catalog for `skill:<name>` references, so a deployed server answers without the skills directory.
 *
 *   node scripts/generate-skill-catalog.mjs           # rewrite the module
 *   node scripts/generate-skill-catalog.mjs --check   # exit 1 when the module is out of date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillsRoot = resolve(packageRoot, "../../skills");
const target = join(packageRoot, "src/operations/skill-catalog.generated.ts");
const manifestPath = join(skillsRoot, "manifest.json");

if (!existsSync(manifestPath)) {
  // A build context without the skills directory keeps the committed module.
  console.warn("skills/manifest.json not found; keeping the committed skill catalog");
  process.exit(0);
}

/** The `description` scalar of a SKILL.md frontmatter block: plain, quoted or folded (`>-`, `|`). */
function description(markdown, id) {
  const block = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(markdown);
  if (!block) throw new Error(`${id}: SKILL.md has no YAML frontmatter`);
  const lines = block[1].split(/\r?\n/);
  for (let index = 0; index < lines.length; index += 1) {
    const top = /^description:(?:[ \t]+(.*))?$/.exec(lines[index]);
    if (!top) continue;
    let value = (top[1] ?? "").trim();
    if (value === "" || /^[>|][+-]?$/.test(value)) {
      const continuation = [];
      while (index + 1 < lines.length && /^(?:[ \t]+\S|[ \t]*$)/.test(lines[index + 1]))
        continuation.push(lines[++index].trim());
      value = continuation.filter(Boolean).join(" ");
    }
    value = value.replace(/^(["'])([\s\S]*)\1$/, "$2").trim();
    if (value) return value;
  }
  throw new Error(`${id}: SKILL.md frontmatter has no description`);
}

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const catalog = manifest.skills.map((skill) => ({
  name: skill.id,
  version: skill.version,
  description: description(readFileSync(join(skillsRoot, skill.path), "utf8"), skill.id),
  surfaces: skill.surfaces ?? [],
  operations: skill.operations ?? [],
}));

const source = `// GENERATED by scripts/generate-skill-catalog.mjs from skills/manifest.json and each skill's SKILL.md.
// Do not edit: change the skill, then run \`corepack pnpm --filter @aiengineer/knowledge-contracts generate\`.

/** One skill as \`describe\` reports it. */
export interface SkillSummary {
  readonly name: string;
  readonly version: string;
  readonly description: string;
  /** The distributions the skill uses (see the manifest's \`distributions\`). */
  readonly surfaces: readonly string[];
  /** The tools and commands the skill covers. */
  readonly operations: readonly string[];
}

export const SKILL_CATALOG: readonly SkillSummary[] = ${JSON.stringify(catalog, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== source) {
    console.error("skill catalog is out of date; run the contracts generator");
    process.exit(1);
  }
} else if (!existsSync(target) || readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== source) {
  writeFileSync(target, source);
}
